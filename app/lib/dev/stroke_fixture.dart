/// 획 픽스처. 점을 촘촘하게 보간하고 손으로 쓴 듯한 결정적 흔들림을 더한다.
Map<String, List<InkStroke>> strokeFixture() {
  final rng = math.Random(7);
  return {
    for (final MapEntry(:key, :value) in _jamo.entries)
      key: [for (final line in value) _densify(line, rng)],
  };
}

InkStroke _densify(_Line line, math.Random rng) {
  const step = 12.0;
  final out = <InkPoint>[];
  for (var i = 0; i < line.length - 1; i++) {
    final (x0, y0) = line[i];
    final (x1, y1) = line[i + 1];
    final len = math.sqrt(math.pow(x1 - x0, 2) + math.pow(y1 - y0, 2));
    final n = math.max(1, (len / step).ceil());
    for (var k = 0; k < n; k++) {
      final t = k / n;
      out.add(InkPoint(x0 + (x1 - x0) * t, y0 + (y1 - y0) * t));
    }
  }
  final (xl, yl) = line.last;
  out.add(InkPoint(xl.toDouble(), yl.toDouble()));
  // 획 전체를 조금 기울이고 옮겨 사람 손 느낌을 낸다.
  final dx = rng.nextDouble() * 20 - 10, dy = rng.nextDouble() * 20 - 10;
  final skew = rng.nextDouble() * 0.06 - 0.03;
  return InkStroke([
    for (final p in out) InkPoint(p.x + dx + p.y * skew, p.y + dy),
  ]);
}
